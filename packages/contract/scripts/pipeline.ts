// Generates the contract (openapi.json) and the TS, Swift and Kotlin clients from packages/api.
// `generate.ts` writes into this package; `check.ts` writes into a temp dir and diffs.
// See ../README.md for the generator choices.

import { execFile } from 'node:child_process';
import { createHash } from 'node:crypto';
import {
  cp,
  mkdir,
  mkdtemp,
  readdir,
  readFile,
  rename,
  rm,
  stat,
  writeFile,
} from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';
import type { OpenAPIHono } from '@hono/zod-openapi';
import { buildOpenApiDocument } from '@trainer-hub/api';
import { generateTypeScriptSchema } from '@trainer-hub/typescript-generator';
// Its own file, so CI can key the cached jar on it (.github/workflows/ci.yml).
import OPENAPI_GENERATOR from '../config/openapi-generator.json' with { type: 'json' };

const run = promisify(execFile);

export const CONTRACT_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** Everything generated, relative to the package root. Nothing else is touched. */
export const GENERATED_PATHS = {
  spec: 'openapi.json',
  typescript: 'src/generated',
  swift: 'swift/Sources/TrainerHubAPI/Generated',
  kotlin: 'kotlin/generated',
} as const;

export const TS_SCHEMA_FILE = 'schema.ts';

const SWIFT_TOOL_PACKAGE = join(CONTRACT_ROOT, 'tools/swift-generator');
const SWIFT_CONFIG = join(CONTRACT_ROOT, 'config/swift-openapi-generator.yaml');
const KOTLIN_CONFIG = join(CONTRACT_ROOT, 'config/kotlin.json');
const CACHE_DIR = join(CONTRACT_ROOT, 'node_modules/.cache/contract');

const TS_BANNER = `/**
 * Generated by openapi-typescript from openapi.json. Do not edit.
 * Regenerate: pnpm --filter @trainer-hub/contract generate
 */

`;

// --- Generators --------------------------------------------------------------------------------

/** Writes openapi.json for `app` (default: the real API) into `outRoot`; returns its path. */
export async function generateSpec(outRoot: string, app?: OpenAPIHono): Promise<string> {
  const file = join(outRoot, GENERATED_PATHS.spec);
  await mkdir(dirname(file), { recursive: true });
  await writeFile(file, `${JSON.stringify(buildOpenApiDocument(app), null, 2)}\n`);
  return file;
}

export async function generateTypeScript(specFile: string, outRoot: string): Promise<void> {
  const source = await generateTypeScriptSchema(JSON.parse(await readFile(specFile, 'utf8')));
  const dir = await resetDir(join(outRoot, GENERATED_PATHS.typescript));
  await writeFile(join(dir, TS_SCHEMA_FILE), TS_BANNER + source);
}

export async function generateSwift(specFile: string, outRoot: string): Promise<void> {
  const generator = await swiftOpenApiGenerator();
  const dir = await resetDir(join(outRoot, GENERATED_PATHS.swift));
  await exec(generator, [
    'generate',
    specFile,
    '--config',
    SWIFT_CONFIG,
    '--output-directory',
    dir,
  ]);
}

export async function generateKotlin(specFile: string, outRoot: string): Promise<void> {
  const jar = await openApiGeneratorJar();
  const staging = await mkdtemp(join(tmpdir(), 'contract-kotlin-'));
  try {
    await exec(javaBinary(), [
      '-jar',
      jar,
      'generate',
      '--input-spec',
      specFile,
      '--generator-name',
      'kotlin',
      '--config',
      KOTLIN_CONFIG,
      '--output',
      staging,
      '--global-property',
      'apiTests=false,modelTests=false,apiDocs=false,modelDocs=false',
    ]);
    // Keep only the sources. The generator's Gradle files, README and metadata don't fit the
    // Android build; E008 compiles these sources in its own module.
    const dir = await resetDir(join(outRoot, GENERATED_PATHS.kotlin));
    await cp(join(staging, 'src/main/kotlin'), dir, { recursive: true });
  } finally {
    await rm(staging, { recursive: true, force: true });
  }
}

/** Generates the spec and every client into `outRoot`. */
export async function generateAll(outRoot: string, log: (line: string) => void): Promise<void> {
  log('openapi.json');
  const specFile = await generateSpec(outRoot);
  // The clients are generated from the file just written, i.e. the one a reviewer reads.
  log('TypeScript client');
  await generateTypeScript(specFile, outRoot);
  log('Swift client');
  await generateSwift(specFile, outRoot);
  log('Kotlin client');
  await generateKotlin(specFile, outRoot);
}

// --- Drift ---------------------------------------------------------------------------------------

export type Drift = { path: string; kind: 'changed' | 'missing' | 'unexpected' };

/**
 * Compares freshly generated files (`expectedRoot`) with the committed ones (`actualRoot`) under
 * each of `paths`. `missing`: not committed; `unexpected`: committed but no longer generated.
 */
export async function findDrift(
  expectedRoot: string,
  actualRoot: string,
  paths: readonly string[],
): Promise<Drift[]> {
  const drift: Drift[] = [];
  for (const path of paths) {
    const expected = await listFiles(expectedRoot, path);
    const actual = await listFiles(actualRoot, path);
    for (const file of new Set([...expected, ...actual])) {
      if (!actual.includes(file)) {
        drift.push({ path: file, kind: 'missing' });
      } else if (!expected.includes(file)) {
        drift.push({ path: file, kind: 'unexpected' });
      } else {
        const [a, b] = await Promise.all([
          readFile(join(expectedRoot, file)),
          readFile(join(actualRoot, file)),
        ]);
        if (!a.equals(b)) drift.push({ path: file, kind: 'changed' });
      }
    }
  }
  return drift.sort((a, b) => a.path.localeCompare(b.path));
}

/** Files under `root/path` (a file or a directory), relative to `root`. */
async function listFiles(root: string, path: string): Promise<string[]> {
  const target = join(root, path);
  const info = await stat(target).catch(() => undefined);
  if (!info) return [];
  if (info.isFile()) return [path];
  const entries = await readdir(target, { recursive: true, withFileTypes: true });
  return entries
    .filter((entry) => entry.isFile() && entry.name !== '.DS_Store')
    .map((entry) => relative(root, join(entry.parentPath, entry.name)))
    .sort();
}

// --- Helpers -------------------------------------------------------------------------------------

async function resetDir(dir: string): Promise<string> {
  await rm(dir, { recursive: true, force: true });
  await mkdir(dir, { recursive: true });
  return dir;
}

async function exec(command: string, args: string[]): Promise<string> {
  try {
    const { stdout } = await run(command, args, { maxBuffer: 64 * 1024 * 1024 });
    return stdout;
  } catch (error) {
    const { stdout = '', stderr = '' } = error as { stdout?: string; stderr?: string };
    throw new Error(`Command failed: ${command} ${args.join(' ')}\n${stdout}${stderr}`, {
      cause: error,
    });
  }
}

function javaBinary(): string {
  const javaHome = process.env.JAVA_HOME;
  return javaHome ? join(javaHome, 'bin/java') : 'java';
}

/**
 * The pinned swift-openapi-generator, built once per Swift toolchain and pinned version and kept
 * in `CACHE_DIR`. A restored `.build` doesn't help: SwiftPM recompiles everything when its files
 * get new inodes, as they do from a CI cache.
 */
async function swiftOpenApiGenerator(): Promise<string> {
  const fingerprint = createHash('sha256').update(await exec('swift', ['--version']));
  for (const file of ['Package.swift', 'Package.resolved']) {
    fingerprint.update(await readFile(join(SWIFT_TOOL_PACKAGE, file)));
  }
  const binary = join(
    CACHE_DIR,
    `swift-openapi-generator-${fingerprint.digest('hex').slice(0, 16)}`,
  );
  if (await stat(binary).catch(() => undefined)) return binary;

  const build = ['build', '-c', 'release', '--package-path', SWIFT_TOOL_PACKAGE];
  await exec('swift', [...build, '--product', 'swift-openapi-generator']);
  const binPath = (await exec('swift', [...build, '--show-bin-path'])).trim();
  await mkdir(CACHE_DIR, { recursive: true });
  // Copy, then rename, so an interrupted copy is never mistaken for a built binary.
  await cp(join(binPath, 'swift-openapi-generator'), `${binary}.partial`);
  await rename(`${binary}.partial`, binary);
  return binary;
}

/** The pinned openapi-generator jar from Maven Central, verified against its SHA-256. */
async function openApiGeneratorJar(): Promise<string> {
  const { version, sha256 } = OPENAPI_GENERATOR;
  const jar = join(CACHE_DIR, `openapi-generator-cli-${version}.jar`);
  const cached = await readFile(jar).catch(() => undefined);
  const bytes = cached ?? (await download(jar, version));
  const actual = createHash('sha256').update(bytes).digest('hex');
  if (actual !== sha256) {
    await rm(jar, { force: true });
    throw new Error(`openapi-generator ${version}: SHA-256 is ${actual}, expected ${sha256}`);
  }
  return jar;
}

async function download(jar: string, version: string): Promise<Buffer> {
  const url = `https://repo1.maven.org/maven2/org/openapitools/openapi-generator-cli/${version}/openapi-generator-cli-${version}.jar`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`Downloading ${url} failed: HTTP ${response.status}`);
  const bytes = Buffer.from(await response.arrayBuffer());
  await mkdir(dirname(jar), { recursive: true });
  await writeFile(jar, bytes);
  return bytes;
}
