import { defaultLocale, type Locale } from '../config.ts';
import type { Analysis } from './analyze.ts';
import { androidName, catalogFile } from './catalog.ts';
import { argIndex, type CompiledMessage, hasArgs, type Part, type PluralCategory } from './icu.ts';

/**
 * Resource folder per locale. The source language goes in the default `values/`. Android
 * would also show it for languages we don't have, so the app picks the language itself and
 * never relies on this resource fallback (ADR-017).
 */
export const androidValuesDir: Record<Locale, string> = { 'nl-NL': 'values', en: 'values-en' };

/**
 * Renders the `strings.xml` of one locale's resource folder.
 *
 * - Keys become snake_case resource names: `notFound.title` → `not_found_title`.
 * - `{name}` → `%1$s`; arguments are numbered in the message's sorted order.
 * - A plural becomes `<plurals>`. Android picks one item for the whole string, so
 *   the text around the plural is repeated in every item; `#` → `%1$d`.
 * - Text is escaped for aapt2 (quotes, `\`, `@`/`?` at the start, whitespace, XML).
 */
export function renderStringsXml(analysis: Analysis, locale: Locale): string {
  const lines = [
    '<?xml version="1.0" encoding="utf-8"?>',
    `<!-- Generated by @trainer-hub/i18n from ${catalogFile(locale)}. Do not edit: change the JSON and run the generator. -->`,
    '<resources>',
  ];
  for (const key of analysis.keys) {
    const message = analysis.compiled[locale].get(key);
    if (!message) throw new Error(`"${key}" is missing in ${locale}; run the checks first`);
    const name = androidName(key);
    const comment = locale === defaultLocale ? analysis.comments.get(key) : undefined;
    if (comment) lines.push(`    <!-- ${xmlComment(comment)} -->`);

    const { body } = message;
    if (body.kind === 'simple') {
      const formatted = hasArgs(message);
      const value = render(message, body.parts, formatted);
      const attribute = !formatted && value.includes('%') ? ' formatted="false"' : '';
      lines.push(`    <string name="${name}"${attribute}>${value}</string>`);
    } else {
      lines.push(`    <plurals name="${name}">`);
      for (const [category, parts] of Object.entries(body.branches) as [PluralCategory, Part[]][]) {
        const value = render(message, [...body.before, ...parts, ...body.after], true, body.arg);
        lines.push(`        <item quantity="${category}">${value}</item>`);
      }
      lines.push('    </plurals>');
    }
  }
  lines.push('</resources>', '');
  return lines.join('\n');
}

function render(
  message: CompiledMessage,
  parts: Part[],
  formatted: boolean,
  pluralArg?: string,
): string {
  const value = parts
    .map((part) => {
      if (part.type === 'text') return escapeText(part.value, formatted);
      const name = part.type === 'count' ? pluralArg : part.name;
      if (name === undefined) throw new Error('# outside a plural');
      const integer = message.args.find((arg) => arg.name === name)?.type === 'integer';
      return `%${argIndex(message, name)}$${integer ? 'd' : 's'}`;
    })
    .join('');
  return escapeWhitespace(value).replace(/^[@?]/, '\\$&');
}

function escapeText(text: string, formatted: boolean): string {
  const escaped = text
    .replaceAll('\\', '\\\\')
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '\\"')
    .replaceAll("'", "\\'")
    .replaceAll('\n', '\\n')
    .replaceAll('\t', '\\t');
  return formatted ? escaped.replaceAll('%', '%%') : escaped;
}

/** aapt2 collapses runs of spaces and trims the ends; ` ` keeps them. */
function escapeWhitespace(value: string): string {
  return value
    .replace(/ {2,}/g, (run) => ` ${'\\u0020'.repeat(run.length - 1)}`)
    .replace(/^ /, '\\u0020')
    .replace(/ $/, '\\u0020');
}

function xmlComment(text: string): string {
  return text.replaceAll('--', '- -').replaceAll('\n', ' ');
}
