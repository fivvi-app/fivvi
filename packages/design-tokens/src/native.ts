const header = (file: string) =>
  `// ${file}: GENERATED by @trainer-hub/design-tokens from tokens/*.json. Do not edit; change the tokens and run \`pnpm --filter @trainer-hub/design-tokens generate\`.\n`;

/**
 * Swift and Kotlin identifier of a token: its path without the group, in lower camel case
 * (`color.action.primary.bg-pressed` → `actionPrimaryBgPressed`, `space.0-5` → `space0_5`).
 */
export function nativeName(tokenPath: string): string {
  const [group = '', ...rest] = tokenPath.split('.');
  const name = rest
    .flatMap((segment) => segment.split('-'))
    .reduce((joined, word, index) => {
      if (index === 0) return word;
      if (/\d$/.test(joined) && /^\d/.test(word)) return `${joined}_${word}`;
      return `${joined}${word.charAt(0).toUpperCase()}${word.slice(1)}`;
    }, '');
  return /^\d/.test(name) ? `${group}${name}` : name;
}

const docComment = (token: ResolvedToken, indent: string) =>
  token.description ? `${indent}/// ${token.description.replaceAll('*/', '* /')}\n` : '';

const kdoc = (token: ResolvedToken, indent: string) =>
  token.description ? `${indent}/** ${token.description.replaceAll('*/', '* /')} */\n` : '';

/** `#RRGGBB` without the `#`; native colours must be opaque, like the contrast check. */
function rgb(token: ResolvedToken): string {
  const hex = token.value.match(/^#([0-9a-f]{6})$/i)?.[1];
  if (!hex) throw new TokenSourceError([`${token.path} is not an opaque #rrggbb colour`]);
  return hex.toUpperCase();
}

/** SwiftUI's `Font.TextStyle` cases and Compose Material 3's `Typography` roles. */
const textStyles: Record<Platform, readonly string[]> = {
  ios: [
    'largeTitle',
    'title',
    'title2',
    'title3',
    'headline',
    'subheadline',
    'body',
    'callout',
    'footnote',
    'caption',
    'caption2',
  ],
  android: ['display', 'headline', 'title', 'body', 'label'].flatMap((role) =>
    ['Large', 'Medium', 'Small'].map((size) => `${role}${size}`),
  ),
};

/** A type style as platform text styles; the note says what to add (weight, figures). */
export interface NativeTextStyle {
  path: string;
  style: Record<Platform, string>;
  note: Record<Platform, string>;
}

/**
 * The platform text style of every type style (`typography.*`), from its mapping note. Native
 * apps use the platform styles so Dynamic Type and font scaling apply; they never set a size.
 */
export function nativeTextStyles(source: TokenSource): NativeTextStyle[] {
  const problems: string[] = [];
  const notes = {
    ios: platformNotes(source.light, 'ios'),
    android: platformNotes(source.light, 'android'),
  };
  const styles = tokenPaths(source.light)
    .filter((tokenPath) => /^typography\.[\w-]+$/.test(tokenPath))
    .map((tokenPath) => {
      const entry = (platform: Platform) => {
        const note = notes[platform].get(tokenPath) ?? '';
        const style = note.match(/^[a-z]\w*/i)?.[0] ?? '';
        if (!textStyles[platform].includes(style)) {
          problems.push(
            `${tokenPath} needs a ${platform} text style (${textStyles[platform].join(', ')}) as its mapping note, not "${note}"`,
          );
        }
        return { style, note };
      };
      const ios = entry('ios');
      const android = entry('android');
      return {
        path: tokenPath,
        style: { ios: ios.style, android: android.style },
        note: { ios: ios.note, android: android.note },
      };
    });
  if (problems.length > 0) throw new TokenSourceError(problems);
  return styles;
}

/** A spacing or radius token in points (iOS) and dp (Android). */
export interface NativeDimension {
  token: ResolvedToken;
  value: number;
}

function dimensions(tokens: ResolvedToken[], group: string): NativeDimension[] {
  return tokens
    .filter((token) => token.path.startsWith(`${group}.`))
    .map((token) => {
      const px = token.value.match(/^(\d+(?:\.\d+)?)px$/)?.[1];
      if (px === undefined) throw new TokenSourceError([`${token.path} is not a px dimension`]);
      return { token, value: Number(px) };
    });
}

/** The Material 3 shape roles, each with the radius token its android note names (`shapes.small`). */
function shapes(source: TokenSource): Map<string, string> {
  const byRole = new Map<string, string>();
  for (const [tokenPath, note] of platformNotes(source.light, 'android')) {
    const role = note.match(/^shapes\.(\w+)$/)?.[1];
    if (tokenPath.startsWith('radius.') && role) byRole.set(role, tokenPath);
  }
  const missing = materialShapes.filter((role) => !byRole.has(role));
  if (missing.length > 0) {
    throw new TokenSourceError(
      missing.map((role) => `No radius token has the android note "shapes.${role}"`),
    );
  }
  return new Map(materialShapes.map((role) => [role, byRole.get(role) ?? '']));
}

export interface NativeInput {
  /** The semantic colours (no palette), in source order, per mode. */
  colours: Record<Mode, ResolvedToken[]>;
  textStyles: NativeTextStyle[];
  spacing: NativeDimension[];
  radius: NativeDimension[];
  /** Material 3 shape role → radius token. */
  shapes: Map<string, string>;
}

/** What the native outputs need from the source and its resolved light tokens. */
export function nativeInput(
  source: TokenSource,
  colours: Record<Mode, ResolvedToken[]>,
  light: ResolvedToken[],
): NativeInput {
  return {
    colours,
    textStyles: nativeTextStyles(source),
    spacing: dimensions(light, 'space'),
    radius: dimensions(light, 'radius'),
    shapes: shapes(source),
  };
}

function renderSwiftTokens(): string {
  return `${header(swiftOutputs.tokens)}
import SwiftUI
#if canImport(UIKit)
import UIKit
#elseif canImport(AppKit)
import AppKit
#endif

/// Trainer Hub's design tokens (ADR-015). Apps use these semantic values, never raw colours or sizes.
public enum Tokens {}

extension Color {
    /// A colour that follows the system appearance: \`light\` in light mode, \`dark\` in dark mode.
    init(light: UInt32, dark: UInt32) {
        #if canImport(UIKit)
        self.init(uiColor: UIColor { traits in
            UIColor(rgb: traits.userInterfaceStyle == .dark ? dark : light)
        })
        #else
        self.init(nsColor: NSColor(name: nil) { appearance in
            NSColor(rgb: appearance.bestMatch(from: [.aqua, .darkAqua]) == .darkAqua ? dark : light)
        })
        #endif
    }
}

#if canImport(UIKit)
private extension UIColor {
    convenience init(rgb: UInt32) {
        self.init(
            red: CGFloat((rgb >> 16) & 0xFF) / 255,
            green: CGFloat((rgb >> 8) & 0xFF) / 255,
            blue: CGFloat(rgb & 0xFF) / 255,
            alpha: 1
        )
    }
}
#else
private extension NSColor {
    convenience init(rgb: UInt32) {
        self.init(
            srgbRed: CGFloat((rgb >> 16) & 0xFF) / 255,
            green: CGFloat((rgb >> 8) & 0xFF) / 255,
            blue: CGFloat(rgb & 0xFF) / 255,
            alpha: 1
        )
    }
}
#endif
`;
}

function renderSwiftColors({ colours }: NativeInput): string {
  const dark = new Map(colours.dark.map((token) => [token.path, token]));
  const members = colours.light.map((token) => {
    const darkToken = dark.get(token.path);
    if (!darkToken) throw new TokenSourceError([`${token.path} has no dark value`]);
    return `${docComment(token, '        ')}        public static let ${nativeName(token.path)} = Color(light: 0x${rgb(token)}, dark: 0x${rgb(darkToken)})`;
  });
  return `${header(swiftOutputs.colors)}
import SwiftUI

public extension Tokens {
    /// Semantic colours. Every one follows the system appearance (light and dark mode).
    enum Colors {
${members.join('\n')}
    }
}
`;
}

function renderKotlinColors({ colours }: NativeInput): string {
  const values = (mode: Mode) =>
    colours[mode].map((token) => `    ${nativeName(token.path)} = Color(0xFF${rgb(token)}),`);
  return `${header(kotlinOutputs.colors)}
package nl.trainerhub.designtokens

import androidx.compose.runtime.Immutable
import androidx.compose.ui.graphics.Color

/**
 * Trainer Hub's semantic colours for one mode (ADR-015). Material 3 components take theirs from
 * [LightColorScheme] and [DarkColorScheme]; use these for what Material doesn't cover.
 */
@Immutable
class TokenColors(
${colours.light.map((token) => `${kdoc(token, '    ')}    val ${nativeName(token.path)}: Color,`).join('\n')}
)

/** The semantic colours in light mode. */
val LightTokenColors: TokenColors = TokenColors(
${values('light').join('\n')}
)

/** The semantic colours in dark mode. */
val DarkTokenColors: TokenColors = TokenColors(
${values('dark').join('\n')}
)
`;
}

function renderKotlinColorSchemes({ colours }: NativeInput): string {
  const known = new Set(colours.light.map((token) => token.path));
  const roles = (tokenColors: string) =>
    Object.entries(materialColours).map(([role, token]) => {
      if (!known.has(token)) throw new TokenSourceError([`${token} is not a semantic colour`]);
      return `    ${role} = ${tokenColors}.${nativeName(token)},`;
    });
  return `${header(kotlinOutputs.colorSchemes)}
package nl.trainerhub.designtokens

import androidx.compose.material3.ColorScheme
import androidx.compose.material3.darkColorScheme
import androidx.compose.material3.lightColorScheme

/** Material 3 colours in light mode, mapped from the semantic tokens. \`scrim\` keeps Material's default. */
val LightColorScheme: ColorScheme = lightColorScheme(
${roles('LightTokenColors').join('\n')}
)

/** Material 3 colours in dark mode, mapped from the semantic tokens. \`scrim\` keeps Material's default. */
val DarkColorScheme: ColorScheme = darkColorScheme(
${roles('DarkTokenColors').join('\n')}
)
`;
}

/** The type style's token, and the mapping note when it says more than the style. */
const styleDoc = (tokenPath: string, style: string, note: string) =>
  note === style ? `\`${tokenPath}\`` : `\`${tokenPath}\`: ${note.replaceAll('*/', '* /')}`;

function renderSwiftTypography({ textStyles }: NativeInput): string {
  const members = textStyles.map(
    ({ path, style, note }) =>
      `        /// ${styleDoc(path, style.ios, note.ios)}\n        public static let ${nativeName(path)}: Font.TextStyle = .${style.ios}`,
  );
  return `${header(swiftOutputs.typography)}
import SwiftUI

public extension Tokens {
    /// The type styles as text styles, so Dynamic Type applies: \`.font(.system(Tokens.TextStyle.body))\`.
    /// Add what the note says (weight, monospaced digits); never set a font size.
    enum TextStyle {
${members.join('\n')}
    }
}
`;
}

function renderKotlinTypography({ textStyles }: NativeInput): string {
  const members = textStyles.map(
    ({ path, style, note }) =>
      `/** ${styleDoc(path, style.android, note.android)} */\nval Typography.${nativeName(path)}: TextStyle\n    get() = ${style.android}`,
  );
  return `${header(kotlinOutputs.typography)}
package nl.trainerhub.designtokens

import androidx.compose.material3.Typography
import androidx.compose.ui.text.TextStyle

// The type styles as Material 3 roles, so font scaling applies: MaterialTheme.typography.body.
// Add what the note says (weight, tabular figures); never set a font size.

${members.join('\n\n')}
`;
}

function renderSwiftLayout({ spacing, radius }: NativeInput): string {
  const members = (values: NativeDimension[]) =>
    values
      .map(
        ({ token, value }) =>
          `${docComment(token, '        ')}        public static let ${nativeName(token.path)}: CGFloat = ${value}`,
      )
      .join('\n');
  return `${header(swiftOutputs.layout)}
import CoreGraphics

public extension Tokens {
    /// Spacing in points: the 4-based scale and the screen margins.
    enum Spacing {
${members(spacing)}
    }

    /// Corner radii in points. Apply them with \`.continuous\` corners.
    enum Radius {
${members(radius)}
    }
}
`;
}

function renderKotlinLayout({ spacing, radius, shapes }: NativeInput): string {
  const members = (values: NativeDimension[]) =>
    values
      .map(
        ({ token, value }) =>
          `${kdoc(token, '    ')}    val ${nativeName(token.path)}: Dp = ${value}.dp`,
      )
      .join('\n');
  return `${header(kotlinOutputs.layout)}
package nl.trainerhub.designtokens

import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.material3.Shapes
import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/** Spacing in dp: the 4-based scale and the screen margins. */
object Spacing {
${members(spacing)}
}

/** Corner radii in dp. */
object Radius {
${members(radius)}
}

/** Material 3 shapes from the radius tokens. */
val TokenShapes: Shapes = Shapes(
${[...shapes].map(([role, token]) => `    ${role} = RoundedCornerShape(Radius.${nativeName(token)}),`).join('\n')}
)
`;
}

/** Every native output, keyed by path relative to the package root. */
export function renderNativeOutputs(input: NativeInput): [string, string][] {
  return [
    [swiftOutputs.tokens, renderSwiftTokens()],
    [swiftOutputs.colors, renderSwiftColors(input)],
    [kotlinOutputs.colors, renderKotlinColors(input)],
    [kotlinOutputs.colorSchemes, renderKotlinColorSchemes(input)],
    [swiftOutputs.typography, renderSwiftTypography(input)],
    [kotlinOutputs.typography, renderKotlinTypography(input)],
    [swiftOutputs.layout, renderSwiftLayout(input)],
    [kotlinOutputs.layout, renderKotlinLayout(input)],
  ];
}
