/** Prefix of every token CSS variable, so they never clash with Tailwind's or shadcn's names. */
const prefix = 'th';

/** shadcn/ui's standard colour variables and the semantic token each one takes. */
export const shadcnColours = {
  background: 'color.bg.canvas',
  foreground: 'color.text.primary',
  card: 'color.bg.surface',
  'card-foreground': 'color.text.primary',
  popover: 'color.bg.raised',
  'popover-foreground': 'color.text.primary',
  primary: 'color.action.primary.bg',
  'primary-foreground': 'color.action.primary.fg',
  secondary: 'color.action.tonal.bg',
  'secondary-foreground': 'color.action.tonal.fg',
  muted: 'color.bg.subtle',
  'muted-foreground': 'color.text.secondary',
  accent: 'color.action.tonal.bg',
  'accent-foreground': 'color.action.tonal.fg',
  destructive: 'color.action.danger.bg',
  'destructive-foreground': 'color.action.danger.fg',
  border: 'color.border.default',
  input: 'color.border.control',
  ring: 'color.border.focus',
} as const;

/** shadcn's `--radius`: the card radius. Tailwind's radius scale is derived from it as in shadcn. */
const shadcnRadius = 'radius.md';

/** Our own theme variables for what shadcn doesn't cover: `--session-*` and `--status-*`. */
const extraColourGroups = /^color\.(session|status)\./;

export interface ResolvedToken {
  /** Dotted token path, e.g. `color.bg.canvas`. */
  path: string;
  /** CSS custom property, e.g. `--th-color-bg-canvas`. */
  name: string;
  value: string;
  description?: string;
}

const header = (file: string) =>
  `/* ${file}: GENERATED by @trainer-hub/design-tokens from tokens/*.json. Do not edit; change the tokens and run \`pnpm --filter @trainer-hub/design-tokens generate\`. */\n`;

/** Resolves every token for one mode with Style Dictionary: references, composites and CSS values. */
async function resolveMode(source: TokenSource, mode: Mode): Promise<ResolvedToken[]> {
  const dictionary = new StyleDictionary({
    tokens: treeFor(source, mode) as DesignTokens,
    usesDtcg: true,
    expand: true,
    log: { verbosity: 'silent' },
    platforms: {
      web: {
        prefix,
        transforms: ['name/kebab', 'color/css', 'fontFamily/css', 'cubicBezier/css'],
      },
    },
  });
  const { allTokens } = await dictionary.getPlatformTokens('web');
  return allTokens.map((token) => {
    const value: unknown = token.$value;
    if (typeof value !== 'string' && typeof value !== 'number') {
      throw new TokenSourceError([
        `${token.path.join('.')} has no CSS value: ${JSON.stringify(value)}`,
      ]);
    }
    return {
      path: token.path.join('.'),
      name: `--${token.name}`,
      value: String(value),
      ...(token.$description ? { description: token.$description } : {}),
    };
  });
}

/** Resolved tokens per mode; throws a TokenSourceError when the source is incomplete. */
export async function resolveTokens(source: TokenSource): Promise<Record<Mode, ResolvedToken[]>> {
  const problems = validate(source);
  if (problems.length > 0) throw new TokenSourceError(problems);
  const [light, dark] = await Promise.all(modes.map((mode) => resolveMode(source, mode)));
  return { light: light ?? [], dark: dark ?? [] };
}

const declarations = (entries: [string, string][], indent: string) =>
  entries.map(([name, value]) => `${indent}${name}: ${value};`).join('\n');

function renderTokensCss(source: TokenSource, resolved: Record<Mode, ResolvedToken[]>): string {
  const colours = new Set(semanticColours(source));
  const light = resolved.light.filter((token) => !isPalette(token.path));
  const dark = resolved.dark.filter((token) => colours.has(token.path));
  return `${header(webOutputs.tokens)}
:root {
  color-scheme: light dark;
${declarations(
  light.map((token) => [token.name, token.value]),
  '  ',
)}
}

@media (prefers-color-scheme: dark) {
  :root {
${declarations(
  dark.map((token) => [token.name, token.value]),
  '    ',
)}
  }
}
`;
}

const extraName = (tokenPath: string) =>
  `--${tokenPath.replace(/^color\./, '').replaceAll('.', '-')}`;

/** Looks up the CSS variable Style Dictionary named for a token. */
type VariableOf = (tokenPath: string) => string;

function variableNames(tokens: ResolvedToken[]): VariableOf {
  const names = new Map(tokens.map((token) => [token.path, token.name]));
  return (tokenPath) => {
    const name = names.get(tokenPath);
    if (!name) throw new TokenSourceError([`${tokenPath} is not a token`]);
    return name;
  };
}

function shadcnVariables(source: TokenSource, cssVar: VariableOf): [string, string][] {
  return [
    ...Object.entries(shadcnColours).map(([name, token]): [string, string] => [
      `--${name}`,
      `var(${cssVar(token)})`,
    ]),
    ['--radius', `var(${cssVar(shadcnRadius)})`],
    ...semanticColours(source)
      .filter((token) => extraColourGroups.test(token))
      .map((token): [string, string] => [extraName(token), `var(${cssVar(token)})`]),
  ];
}

function renderShadcnCss(source: TokenSource, cssVar: VariableOf): string {
  return `${header(webOutputs.shadcn)}
/* shadcn/ui theme variables. They reference the token variables, so they follow light and dark mode. */
:root {
${declarations(shadcnVariables(source, cssVar), '  ')}
}
`;
}

function renderTailwindTheme(source: TokenSource, cssVar: VariableOf): string {
  const colours = shadcnVariables(source, cssVar).filter(([name]) => name !== '--radius');
  return `${header(webOutputs.theme)}
/* Tailwind v4 theme: utilities such as bg-primary or text-session-private-fg use the theme variables. */
@theme inline {
${declarations(
  colours.map(([name]) => [`--color-${name.slice(2)}`, `var(${name})`]),
  '  ',
)}
  --radius-sm: calc(var(--radius) - 4px);
  --radius-md: calc(var(--radius) - 2px);
  --radius-lg: var(--radius);
  --radius-xl: calc(var(--radius) + 4px);
  --font-sans: var(${cssVar('font.family.text')});
}
`;
}

/** Every generated file, keyed by path relative to the package root. */
export async function renderOutputs(source: TokenSource): Promise<Map<string, string>> {
  const resolved = await resolveTokens(source);
  const cssVar = variableNames(resolved.light);
  const colours = new Set(semanticColours(source));
  const semantic = (mode: Mode) => resolved[mode].filter((token) => colours.has(token.path));
  return new Map([
    [webOutputs.tokens, renderTokensCss(source, resolved)],
    [webOutputs.shadcn, renderShadcnCss(source, cssVar)],
    [webOutputs.theme, renderTailwindTheme(source, cssVar)],
    ...renderNativeOutputs({ colours: { light: semantic('light'), dark: semantic('dark') } }),
  ]);
}

export async function writeOutputs(root: string, source: TokenSource): Promise<string[]> {
  const files = await renderOutputs(source);
  for (const [file, content] of files) {
    await mkdir(path.dirname(path.join(root, file)), { recursive: true });
    await writeFile(path.join(root, file), content);
  }
  return [...files.keys()];
}
