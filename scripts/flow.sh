#!/usr/bin/env bash
# Where an issue is in the flow, and the mechanical steps between phases. The `work` skill drives this.
#
#   flow.sh status <n>                      facts, phase and next step for an issue
#   flow.sh facts <n>                       the facts as JSON (input of scripts/flow-phase.jq)
#   flow.sh next                            your open issues with their phase, the open specs, the ready tickets, the
#                                           approved specs to cut (Cut #n) and answered needs-info questions, then
#                                           what waits on the owner: specs to approve, owner-only PRs, PRs the merge
#                                           gate refused, PRs GitHub removed from the merge queue, unanswered
#                                           questions; last, what the owner may read: the high-risk PRs agents merged
#                                           in the last 7 days (ADR-021)
#   flow.sh idle                            exit 0 and "idle: nothing for an agent" (plus what waits on the owner) when no
#                                           agent has anything to do: nothing under "Ready for an agent" in `next` and no
#                                           issue assigned to you in a phase an agent acts on; exit 1 and what there is
#                                           otherwise; exit 2 on every error (a bad argument and a missing tool
#                                           included), never a false idle. A cheap check for the scheduled factory run,
#                                           right after `lock acquire`
#   flow.sh start <n> [--type <t>] [--force]  claim a ready ticket and create its <type>/<n>-<slug> worktree and notes;
#                                           no limit on the tickets in progress, unless FIVVI_MAX_TICKETS (a positive
#                                           integer) sets one: then it refuses at that many (--force to override)
#   flow.sh finish <n>                      after its PR is merged (it says so when the PR is still in
#                                           the merge queue, or GitHub removed it): remove worktree, branches and the
#                                           worktree's iOS simulator, close the issue, report what the spec needs next
#   flow.sh lock acquire|status             the run lock of the factory (work skill, Factory): one run at a time. A file
#   flow.sh lock refresh|release <run-id>   under the main checkout's .work/ (outside git, shared by all worktrees;
#                                           FIVVI_RUN_LOCK overrides the path), expiring 3 hours after it was taken or
#                                           last refreshed, so a crashed run does not stop the factory. acquire fails
#                                           with the lock's age while a run holds it, takes over an expired one and
#                                           prints the run id; refresh renews the time and release frees the lock,
#                                           both only for the run whose id they are given, and fail when the lock is
#                                           missing or another run holds it; status says free, live or expired
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/_lib.sh"

# `idle` answers with its exit status: 0 idle, 1 work, 2 an error. Every other way out of the script, whatever fails
# (a bad argument, a missing tool, a die), becomes 2: an error must never read as "work, carry on" or as idle.
IDLE_ANSWERED=false
if [ "${1:-}" = idle ]; then
  idle_exit() { local rc=$?; $IDLE_ANSWERED || [ "$rc" -eq 0 ] || exit 2; }
  trap idle_exit EXIT
fi

usage() { usage_of "$0"; }

need_cmd gh
need_cmd jq
REPO="$(repo_slug)"
[ -n "$REPO" ] || die "could not read the GitHub repository from the origin remote"
OWNER="${REPO%%/*}"
NAME="${REPO#*/}"
PHASE_JQ="$ROOT/scripts/flow-phase.jq"
# A needs-info question is answered once the newest comment is not a triage note: every comment the triage skill
# posts starts with its AI disclaimer. The agent and the owner share one GitHub account, so the author can't tell.
ANSWERED_JQ='def answered: (.comments // []) | length > 0
  and (last.body | test("^\\s*>\\s*\\*This was generated by AI during triage") | not);'

is_number() { [[ "${1:-}" =~ ^[0-9]+$ ]] || die "not an issue number: ${1:-<missing>}"; }

ME=""
# Who you are. Dies on a failed or empty read, so a failure can't pass for "nobody": call it as `x="$(me)" || exit 1`
# (a die in the command substitution only ends that subshell).
me() {
  if [ -z "$ME" ]; then
    ME="$(gh api user --jq .login)" || die "could not read who you are (gh api user)"
    [ -n "$ME" ] || die "could not read who you are (gh api user)"
  fi
  echo "$ME"
}

FETCHED=false
fetch_once() {
  $FETCHED && return
  git -C "$MAIN_ROOT" fetch --prune --quiet 2>/dev/null || true
  FETCHED=true
}

# Every local or remote <type>/<n>-* branch.
issue_branches() {
  fetch_once
  git -C "$MAIN_ROOT" for-each-ref --format='%(refname)' "refs/heads/*/$1-*" "refs/remotes/origin/*/$1-*" \
    | sed -E 's#^refs/(heads|remotes/origin)/##' | grep -E "^[a-z]+/$1-" | sort -u || true
}

pr_facts() {
  local branch="$1" pr number threads risk refusal queue
  pr="$(gh pr list --repo "$REPO" --head "$branch" --state all \
    --json number,state,isDraft,reviewDecision,statusCheckRollup,url,createdAt,headRefOid \
    --jq 'sort_by(.number) | last // empty')"
  [ -n "$pr" ] || { echo null; return; }
  number="$(jq -r .number <<<"$pr")"
  threads=0 risk=null refusal=null queue=null
  if [ "$(jq -r .state <<<"$pr")" = OPEN ]; then
    risk="$("$ROOT/scripts/risk.sh" "$number" --json 2>/dev/null)" || risk=null
    # A refusal of the merge gate for the head commit makes the PR wait on the owner (flow-phase.jq).
    refusal="$("$ROOT/scripts/pr.sh" refusal "$number")" || die "could not read the refusal of PR #$number"
    # In the merge queue, or removed from it by GitHub (scripts/pr.sh queue, ADR-018).
    queue="$("$ROOT/scripts/pr.sh" queue "$number")" || die "could not read the merge queue state of PR #$number"
    # shellcheck disable=SC2016 # GraphQL variables, not shell
    threads="$(gh api graphql -F owner="$OWNER" -F name="$NAME" -F n="$number" -f query='
      query($owner: String!, $name: String!, $n: Int!) {
        repository(owner: $owner, name: $name) { pullRequest(number: $n) { reviewThreads(first: 100) { nodes { isResolved } } } }
      }' --jq '[.data.repository.pullRequest.reviewThreads.nodes[] | select(.isResolved | not)] | length')"
  fi
  # GitHub reports unfinished conclusions and a missing review as "", not null.
  jq --argjson threads "$threads" --argjson risk "$risk" --argjson refusal "$refusal" --argjson queue "$queue" \
    'def value(f): [f[] | select(. != null and . != "")] | first // "";
    {
    number, state, url, draft: .isDraft, threads: $threads, risk: $risk.risk, risk_reasons: ($risk.reasons // []),
    head: .headRefOid, refusal: $refusal, queue: $queue,
    review: (if (.reviewDecision // "") == "" then null else .reviewDecision end),
    failing: [.statusCheckRollup[]? | select(value([.conclusion, .state])
      | IN("FAILURE", "ERROR", "TIMED_OUT", "CANCELLED", "ACTION_REQUIRED", "STARTUP_FAILURE"))] | length,
    pending: [.statusCheckRollup[]? | select(value([.conclusion, .state]) == ""
      or (.state // "" | IN("PENDING", "EXPECTED")))] | length,
    age_days: ((now - (.createdAt | fromdateiso8601)) / 86400 | floor)}' <<<"$pr"
}

branch_facts() {
  local branch="$1" local_ref=false wt dirty=0 ahead ref
  wt="$(worktree_of "$branch")"
  ref="origin/$branch"
  if git -C "$MAIN_ROOT" show-ref --verify --quiet "refs/heads/$branch"; then local_ref=true; ref="$branch"; fi
  [ -z "$wt" ] || dirty="$(git -C "$wt" status --porcelain | wc -l | tr -d ' ')"
  ahead="$(git -C "$MAIN_ROOT" rev-list --count "origin/$(default_branch)..$ref" 2>/dev/null || echo null)"
  jq -n --arg name "$branch" --argjson local "$local_ref" --arg wt "${wt#"$MAIN_ROOT"/}" --argjson dirty "$dirty" \
    --argjson ahead "$ahead" --argjson pr "$(pr_facts "$branch")" \
    '{name: $name, local: $local, worktree: (if $wt == "" then null else $wt end), dirty: $dirty, ahead: $ahead, pr: $pr}'
}

child_facts() {
  gh issue view "$1" --repo "$REPO" --json number,title,state,labels,assignees,blockedBy --jq '{number, title, state,
    labels: [.labels[].name], assignees: [.assignees[].login],
    blocked: ([.blockedBy.nodes[] | select(.state == "OPEN")] | length > 0)}'
}

facts() {
  local n="$1" item parent=null children="[]" branches="[]" child branch p login
  login="$(me)" || return 1
  item="$(gh issue view "$n" --repo "$REPO" --json number,title,state,labels,assignees,body,comments,parent,subIssues,blockedBy)"
  for child in $(jq -r '.subIssues.nodes[].number' <<<"$item"); do
    children="$(jq --argjson c "$(child_facts "$child")" '. + [$c]' <<<"$children")"
  done
  p="$(jq -r '.parent.number // empty' <<<"$item")"
  if [ -n "$p" ]; then
    parent="$(gh issue view "$p" --repo "$REPO" --json number,title,state,labels,subIssues --jq '{number, title, state,
      labels: [.labels[].name], open: ([.subIssues.nodes[] | select(.state == "OPEN")] | length),
      total: .subIssues.totalCount}')"
  fi
  for branch in $(issue_branches "$n"); do
    branches="$(jq --argjson b "$(branch_facts "$branch")" '. + [$b]' <<<"$branches")"
  done
  jq --arg me "$login" --argjson parent "$parent" --argjson children "$children" --argjson branches "$branches" "$ANSWERED_JQ"'{
    number, title, state, me: $me, answered: answered,
    labels: [.labels[].name], assignees: [.assignees[].login],
    described: ((.body // "") | gsub("\\s"; "") | length > 0),
    has_criteria: ((.body // "") | test("(^|\\n)#+\\s*acceptance criteria|(^|\\n)\\s*- \\[[ x]\\]"; "i")),
    parent: $parent, children: $children, branches: $branches,
    blockers: [.blockedBy.nodes[] | select(.state == "OPEN") | {number, title}]}' <<<"$item"
}

render() {
  jq -r --arg notes "$2" --argjson d "$(jq -f "$PHASE_JQ" <<<"$1")" '
    def ref: "#\(.number) \(.state) — \(.title)";
    "#\(.number) \(.state) — \(.title)",
    "Labels: \(.labels | join(", "))",
    "Assignees: \(.assignees | join(", "))",
    (.parent // empty | "Parent: \(ref) · \(.open) of \(.total) tickets open"),
    (if (.blockers | length) == 0 then "Blocked by: none" else "Blocked by:", (.blockers[] | "  #\(.number) — \(.title)") end),
    (if (.children | length) == 0 then empty else "Tickets:",
      (.children[] | "  \(ref)\(if (.labels | length) > 0 then " [\(.labels | join(", "))]" else "" end)\(if (.assignees | length) > 0 then " (\(.assignees | join(", ")))" else "" end)\(if .blocked then " ⛓" else "" end)") end),
    (.branches[] | "Branch: \(.name)\(if .ahead != null then " · \(.ahead) ahead of main" else "" end)\(if .worktree then " · worktree \(.worktree) · \(if .dirty == 0 then "clean" else "\(.dirty) uncommitted" end)" else "" end)",
      (.pr // empty | "PR: #\(.number) \(.state)\(if .draft then " draft" else "" end) · \(.age_days) days old · failing checks \(.failing) · pending \(.pending) · open threads \(.threads) · review \(.review // "none")\(if .risk == "owner" then " · owner-only" elif .risk then " · \(.risk)-risk" else "" end)\(if .queue.state == "queued" then " · in the merge queue (position \(.queue.position))" elif .queue.state == "removed" then " · removed from the merge queue (\(.queue.reason // "no reason given"))" else "" end) · \(.url)",
        (.risk as $risk | .risk_reasons[]? | "  \(if $risk == "owner" then "owner-only" else "high-risk" end): \(.)"))),
    (if $notes != "" then "Notes: \($notes)" else empty end),
    "Phase: \($d.phase)",
    "Next: \($d.next)",
    (if $d.hint != "" then "Hint: \($d.hint)" else empty end)' <<<"$1"
}

notes_of() { [ ! -f "$NOTES_DIR/$1/notes.md" ] || echo "$NOTES_DIR/$1/notes.md"; }

cmd_status() {
  [ $# -eq 1 ] || usage
  is_number "$1"
  render "$(facts "$1")" "$(notes_of "$1")"
}

cmd_facts() {
  [ $# -eq 1 ] || usage
  is_number "$1"
  facts "$1"
}

# Your open issues, one line each, separated by | (the title comes last, so it may contain one): number, phase, the head commits of its PRs that GitHub removed from
# the merge queue (comma-separated, empty otherwise) and the title. Dies when a read fails.
assigned_lines() {
  local mine n f phase heads
  mine="$(gh issue list --repo "$REPO" --assignee @me --state open --json number --jq '.[].number')" \
    || die "could not read the issues assigned to you"
  for n in $mine; do
    f="$(facts "$n")" || die "could not read #$n"
    phase="$(facts_phase "$f")" || die "could not read the phase of #$n"
    heads="$(jq -r '[.branches[].pr | select(. != null and .state == "OPEN" and .queue.state == "removed") | .head] | join(",")' <<<"$f")" \
      || die "could not read the merge queue state of #$n"
    printf '%s|%s|%s|%s\n' "$n" "$phase" "$heads" "$(jq -r .title <<<"$f")"
  done
}

# The phase flow-phase.jq decides from the facts $1 of an issue; fails when there is none.
facts_phase() {
  local d
  d="$(jq -f "$PHASE_JQ" <<<"$1")" || return 1
  jq -er .phase <<<"$d"
}

read_specs() {
  gh issue list --repo "$REPO" --label "$SPEC_LABEL" --state open --limit 200 \
    --json number,title,body,labels,subIssuesSummary || die "could not read the open specs"
}

read_questions() {
  gh issue list --repo "$REPO" --label needs-info --state open --limit 100 --json number,title,comments \
    --jq "$ANSWERED_JQ"'.[] | {number, title, answered: answered}' || die "could not read the needs-info questions"
}

# What an agent can start without the owner: the ready tickets (scripts/issue.sh ready), the approved specs without
# tickets that flow-phase.jq calls needs-tickets (`Cut #n`; facts are read only for such candidates, so a spec that has
# tickets or is not approved costs no read) and the needs-info questions that were answered. $1 is read_specs, $2
# read_questions. Dies when a read fails, so an empty list means nothing is ready.
ready_items() {
  local ready candidates n title f phase
  ready="$("$ROOT/scripts/issue.sh" ready)" || die "could not read the ready tickets"
  candidates="$(jq -r --arg approved "$APPROVED_LABEL" '.[]
    | select(([.labels[].name] | index($approved)) and .subIssuesSummary.total == 0)
    | "\(.number)\t\(.title)"' <<<"$1")" || die "could not read the open specs"
  awk -F'\t' 'NF { print "#" $1 " " $2 }' <<<"$ready"
  while IFS=$'\t' read -r n title; do
    [ -n "$n" ] || continue
    f="$(facts "$n")" || die "could not read #$n"
    phase="$(facts_phase "$f")" || die "could not read the phase of #$n"
    [ "$phase" != needs-tickets ] || echo "Cut #$n $title ($phase)"
  done <<<"$candidates"
  jq -r 'select(.answered) | "Triage #\(.number) \(.title) (answered)"' <<<"$2"
}

cmd_next() {
  [ $# -eq 0 ] || usage
  local specs questions ready owner read_items mine n phase heads title
  echo "== Assigned to you"
  mine="$(assigned_lines)" || exit 1
  if [ -z "$mine" ]; then echo "(none)"; fi
  while IFS='|' read -r n phase heads title; do
    [ -z "$n" ] || echo "#$n $title → $phase"
  done <<<"$mine"
  echo "== Open specs"
  specs="$(read_specs)" || exit 1
  jq -r 'if length == 0 then "(none)" else .[] | "#\(.number) \(.title) — \(.subIssuesSummary.completed) of \(.subIssuesSummary.total) tickets done" end' <<<"$specs"
  echo "== Ready for an agent"
  # Read first, then print: a failed read is an error, never "(none)".
  questions="$(read_questions)" || exit 1
  ready="$(ready_items "$specs" "$questions")" || exit 1
  grep . <<<"$ready" || echo "(none)"
  echo "== Waiting on the owner"
  owner="$(owner_items "$specs" "$questions")" || exit 1
  grep . <<<"$owner" || echo "(none)"
  echo "== For the owner to read"
  read_items="$(agent_merged_items)" || exit 1
  grep . <<<"$read_items" || echo "(none)"
}

# The phases the work skill's playbook leaves to the owner, GitHub or the user; queue-removed is work until the notes say
# the owner was told about the PR's head commit. Any other phase counts as work, so an unknown one is never a false idle.
WAITING_PHASES=" queued merge-refused in-review approved waiting needs-approval needs-spec needs-refinement human blocked taken abandoned done "

# True when the notes of #$1 have `queue-removed <sha>: reported to the owner` (an optional "- " before it) for every
# head commit in $2 (comma-separated); <sha> is the commit or a prefix of it of at least 7 hex characters.
removal_reported() {
  local n="$1" notes head sha found
  notes="$(notes_of "$n")"
  [ -n "$notes" ] && [ -n "${2:-}" ] || return 1
  for head in ${2//,/ }; do
    found=false
    while IFS= read -r sha; do
      case "$head" in "$sha"*) found=true; break ;; esac
    done < <(sed -nE 's/^(- )?queue-removed ([0-9a-f]{7,40}): reported to the owner.*/\2/p' "$notes")
    $found || return 1
  done
}

# The scan of `idle`: the first line is `work` or `idle`, then the lines that explain it. Dies when a read fails.
idle_scan() {
  local specs questions ready mine owner work='' n phase heads title
  mine="$(assigned_lines)" || exit 1
  while IFS='|' read -r n phase heads title; do
    [ -n "$n" ] || continue
    case "$WAITING_PHASES" in *" $phase "*) continue ;; esac
    if [ "$phase" = queue-removed ] && removal_reported "$n" "$heads"; then continue; fi
    work+="#$n $title → $phase"$'\n'
  done <<<"$mine"
  specs="$(read_specs)" || exit 1
  questions="$(read_questions)" || exit 1
  ready="$(ready_items "$specs" "$questions")" || exit 1
  work+="$ready"
  if grep -q . <<<"$work"; then
    echo work
    grep . <<<"$work"
  else
    owner="$(owner_items "$specs" "$questions")" || exit 1
    echo idle
    echo "== Waiting on the owner"
    grep . <<<"$owner" || echo "(none)"
  fi
}

# Exit 0 when nothing is for an agent, 1 when there is, 2 on an error. The scan runs apart, so a die (exit 1) in it
# can't pass for "there is work", and nothing is printed as idle before the scan is done.
cmd_idle() {
  [ $# -eq 0 ] || usage
  local out
  out="$(idle_scan)" || exit 2
  IDLE_ANSWERED=true
  if [ "$(head -n 1 <<<"$out")" = idle ]; then
    echo "idle: nothing for an agent"
    tail -n +2 <<<"$out"
    exit 0
  fi
  tail -n +2 <<<"$out"
  exit 1
}

# Now as seconds since the epoch: the real clock, or FIVVI_NOW (ISO-8601 UTC, like 2026-10-20T12:00:00Z) so tests and
# reruns don't depend on it. Dies on a FIVVI_NOW that is set but not such a time (set-but-empty included), never
# falls back to the real clock.
now_epoch() {
  local now
  if [ -n "${FIVVI_NOW+set}" ]; then
    now="$FIVVI_NOW"
  else
    now="$(date -u +%Y-%m-%dT%H:%M:%SZ)" || die "could not read the clock"
  fi
  [[ "$now" =~ ^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}Z$ ]] \
    || die "FIVVI_NOW must be an ISO-8601 UTC time like 2026-10-20T12:00:00Z, not '$now'"
  jq -rn --arg now "$now" '$now | fromdateiso8601' 2>/dev/null \
    || die "FIVVI_NOW must be an ISO-8601 UTC time like 2026-10-20T12:00:00Z, not '$now'"
}

# The high-risk PRs agents merged in the last 7 days (ADR-021), newest first, from the record pr.sh merge writes in the
# PR body before it queues the PR: `**High-risk agent merge:** `<sha>`: <reasons>`. A PR counts when the commit GitHub
# merged (the PR's headRefOid) is the recorded one, whether it went through the merge queue or was squash-merged at
# once: if another commit was merged (the queue dropped the recorded one and the owner merged a later one), the owner
# merged it. The owner reads them after the fact. A search by day narrows what GitHub returns and jq applies the exact
# 7 days (a PR merged exactly 7 days ago counts); the 200 latest merged PRs are enough for a week. Dies when the read
# fails, so an empty list means nothing was merged.
agent_merged_items() {
  local now since merged
  now="$(now_epoch)" || exit 1
  since="$(jq -rn --argjson now "$now" '$now - 7 * 86400 | strftime("%Y-%m-%d")')" \
    || die "could not compute the date 7 days ago"
  merged="$(gh pr list --repo "$REPO" --state merged --search "merged:>=$since" --limit 200 \
    --json number,title,body,mergedAt,headRefOid)" || die "could not read the merged PRs"
  jq -r -L "$ROOT/scripts" --arg risk "$HIGH_RISK_MARK" --argjson now "$now" '
    include "records";
    [.[] | select((.mergedAt | fromdateiso8601) >= $now - 7 * 86400)
      | {number, title, mergedAt, head: .headRefOid, record: (.body | record($risk))}
      | select(.record != null and .head != null and (.record | record_sha) == .head)]
    | sort_by(.mergedAt) | reverse | .[]
    | "PR #\(.number) \(.title) (merged by an agent; high-risk: \(.record
        | record_reasons // "reasons not recorded"))"' <<<"$merged" \
    || die "could not read the merged PRs"
}

# Specs to approve, owner-only PRs (scripts/risk.sh; an unknown risk counts as owner-only), PRs GitHub removed from the
# merge queue (scripts/pr.sh queue), low-risk and high-risk PRs the merge gate refused on their head commit
# (scripts/pr.sh refusal) and unanswered needs-info questions ($2, from cmd_next). A PR in the merge queue waits on
# GitHub, not on the owner. A spec is to approve when flow-phase.jq would call it needs-approval: not approved, not
# complete, and not still needs-spec (no tickets, not ready-for-agent, and needs-triage or no body). Dies when a read
# fails, so an empty list means nothing waits.
owner_items() {
  local prs pr title head risk refusal queue
  jq -r --arg approved "$APPROVED_LABEL" --arg ready "$READY_LABEL" '.[]
    | [.labels[].name] as $labels
    | ((.body // "") | gsub("\\s"; "") | length > 0) as $described
    | select($labels | index($approved) | not)
    | select((.subIssuesSummary.total > 0 and .subIssuesSummary.completed == .subIssuesSummary.total) | not)
    | select((.subIssuesSummary.total == 0 and ($labels | index($ready) | not)
        and (($labels | index("needs-triage")) or ($described | not))) | not)
    | "Approve spec #\(.number) \(.title) (add \($approved))"' <<<"$1" || die "could not read the open specs"
  prs="$(gh pr list --repo "$REPO" --state open --limit 100 --json number,title,isDraft,headRefOid \
    --jq '.[] | select(.isDraft | not) | [.number, .title, .headRefOid] | @tsv')" || die "could not read the open PRs"
  while IFS=$'\t' read -r pr title head; do
    [ -n "$pr" ] || continue
    queue="$("$ROOT/scripts/pr.sh" queue "$pr")" || die "could not read the merge queue state of PR #$pr"
    case "$(jq -r '.state // ""' <<<"$queue")" in
      queued) continue ;;
      removed)
        jq -r --arg pr "$pr" --arg title "$title" \
          '"Decide on PR #\($pr) \($title) (GitHub removed it from the merge queue: \(.reason // "no reason given"); or fix it and push)"' <<<"$queue" \
          || die "could not read the merge queue state of PR #$pr"
        continue ;;
    esac
    risk="$("$ROOT/scripts/risk.sh" "$pr" --json)" || risk='{"risk": "owner", "reasons": ["risk unknown"]}'
    if [ "$(jq -r .risk <<<"$risk")" = owner ]; then
      jq -r --arg pr "$pr" --arg title "$title" \
        '"Merge PR #\($pr) \($title) (owner-only: \(.reasons[:3] | join("; "))\(if (.reasons | length) > 3 then "; +\(.reasons | length - 3) more" else "" end))"' <<<"$risk" \
        || die "could not read the risk of PR #$pr"
      continue
    fi
    refusal="$("$ROOT/scripts/pr.sh" refusal "$pr")" || die "could not read the refusal of PR #$pr"
    jq -r --arg pr "$pr" --arg title "$title" --arg head "$head" \
      'select(. != null and .sha != null and .sha == $head)
       | "Decide on PR #\($pr) \($title) (the merge gate refused it on \($head[:7]): \(.reasons); or fix it and push)"' \
      <<<"$refusal" || die "could not read the refusal of PR #$pr"
  done <<<"$prs"
  jq -r 'select(.answered | not) | "Answer #\(.number) \(.title) (needs-info)"' <<<"$2"
}

# The most tickets in progress at once, if the session sets a limit (ADR-021): FIVVI_MAX_TICKETS, a positive integer.
# There is no default. Dies on any other value, set but empty included: a typo must not turn the limit off.
max_tickets() {
  [ -n "${FIVVI_MAX_TICKETS+set}" ] || return 0
  [[ "$FIVVI_MAX_TICKETS" =~ ^[1-9][0-9]*$ ]] || die "FIVVI_MAX_TICKETS must be a positive integer, not '$FIVVI_MAX_TICKETS'"
  echo "$FIVVI_MAX_TICKETS"
}

tickets_in_progress() {
  git -C "$MAIN_ROOT" worktree list --porcelain \
    | sed -nE 's#^branch refs/heads/([a-z]+/[0-9]+-.*)$#\1#p' | wc -l | tr -d ' '
}

cmd_start() {
  local n="" type="" force=false f d phase branch wt title max login
  while [ $# -gt 0 ]; do
    case "$1" in
      --type) type="${2:?}"; shift ;;
      --force) force=true ;;
      *) [ -z "$n" ] || usage; n="$1" ;;
    esac
    shift
  done
  is_number "$n"
  max="$(max_tickets)" || exit 1
  f="$(facts "$n")"
  d="$(jq -f "$PHASE_JQ" <<<"$f")"
  phase="$(jq -r .phase <<<"$d")"
  case "$phase" in
    ready|in-progress) ;;
    taken) die "#$n: $(jq -r .next <<<"$d")" ;;
    *) $force || die "#$n is '$phase', not ready: $(jq -r .next <<<"$d") (pass --force to start anyway)" ;;
  esac

  branch="$(jq -r '.branches[0].name // empty' <<<"$f")"
  if [ -z "$branch" ]; then
    if [ -n "$max" ] && [ "$(tickets_in_progress)" -ge "$max" ] && ! $force; then
      die "$max tickets are already in progress (scripts/wt.sh list, FIVVI_MAX_TICKETS=$max); finish one first, unset FIVVI_MAX_TICKETS, or pass --force"
    fi
    title="$(jq -r .title <<<"$f")"
    if [ -z "$type" ]; then
      if jq -e '.labels | index("bug")' <<<"$f" >/dev/null; then type=fix
      elif [[ "$title" =~ ^\[E[0-9]+\] ]]; then type=chore
      else type=feature
      fi
    fi
    case " $BRANCH_TYPES " in *" $type "*) ;; *) die "--type must be one of: $BRANCH_TYPES" ;; esac
    branch="$type/$n-$(slugify "$title")"
  fi

  login="$(me)" || exit 1
  jq -e --arg me "$login" '.assignees | index($me)' <<<"$f" >/dev/null || "$ROOT/scripts/issue.sh" claim "$n"
  mkdir -p "$NOTES_DIR/$n"
  [ -f "$NOTES_DIR/$n/notes.md" ] || printf '# #%s %s\n' "$n" "$(jq -r .title <<<"$f")" > "$NOTES_DIR/$n/notes.md"
  wt="$(worktree_of "$branch")"
  if [ -n "$wt" ]; then echo "↻ worktree exists: ${wt#"$MAIN_ROOT"/}"; else "$ROOT/scripts/wt.sh" add "$branch"; wt="$(worktree_of "$branch")"; fi
  echo "Worktree: $wt"
  echo "Notes: $NOTES_DIR/$n/notes.md"
  echo "E2E_PORT: $(e2e_port "$wt")"
  [ "$(jq -r .hint <<<"$d")" = "" ] || echo "Hint: $(jq -r .hint <<<"$d")"
}

cmd_finish() {
  [ $# -eq 1 ] || usage
  is_number "$1"
  local n="$1" f branch wt pr parent
  f="$(facts "$n")"
  [ "$(jq '.branches | length' <<<"$f")" -gt 0 ] || die "#$n has no branches"
  # GitHub merges a PR in the merge queue by itself, so the cleanup waits for it; a removal needs a decision first.
  ! jq -e 'any(.branches[].pr; .state == "OPEN" and .queue.state == "queued")' <<<"$f" >/dev/null \
    || die "#$n: its PR is in the merge queue: wait until GitHub has merged it (scripts/flow.sh status $n), then finish"
  ! jq -e 'any(.branches[].pr; .state == "OPEN" and .queue.state == "removed")' <<<"$f" >/dev/null \
    || die "#$n: GitHub removed its PR from the merge queue, so nothing is merged yet (scripts/flow.sh status $n)"
  jq -e '[.branches[].pr.state] | all(. == "MERGED")' <<<"$f" >/dev/null || die "#$n: not every branch has a merged PR"

  for branch in $(jq -r '.branches[].name' <<<"$f"); do
    wt="$(worktree_of "$branch")"
    if [ -n "$wt" ] && [ "$wt" != "$MAIN_ROOT" ]; then
      case "$ROOT/" in "$wt/"*) die "run flow.sh finish from the main checkout, not from $branch's worktree" ;; esac
    fi
    "$ROOT/scripts/wt.sh" "done" "$branch" --check
  done
  for branch in $(jq -r '.branches[].name' <<<"$f"); do "$ROOT/scripts/wt.sh" "done" "$branch"; done

  if [ "$(gh issue view "$n" --repo "$REPO" --json state --jq .state)" = OPEN ]; then
    pr="$(jq -r '[.branches[].pr.url] | join(", ")' <<<"$f")"
    "$ROOT/scripts/issue.sh" close "$n" --comment "Done in $pr."
  fi
  rm -rf "${NOTES_DIR:?}/$n"
  echo "✅ #$n done"

  parent="$(jq -r '.parent.number // empty' <<<"$f")"
  [ -n "$parent" ] || return 0
  f="$(facts "$parent")"
  echo "Spec #$parent: $(jq -r .phase <<<"$(jq -f "$PHASE_JQ" <<<"$f")") — $(jq -r .next <<<"$(jq -f "$PHASE_JQ" <<<"$f")")"
}

# The run lock (spec #292, scheduled runs). One line: the time it was taken or last refreshed (ISO-8601 UTC), who took it
# and the run id that acquire printed (`<time> <user@host> pid <n> run <id>`); refresh and release must be given that id,
# so a run never renews or frees the lock of another. Written to a temporary file and linked into place (`ln` fails when
# the lock exists), so a second run never sees a half-written lock and only one of two racing runs wins. An expired lock,
# and the lock a refresh replaces, is first seized: renamed to a name of this run alone (only one run can win a rename),
# and its line compared with the line that was read. A run that seized a different lock (another run was faster) puts it
# back with `ln` and loses. Known limit (ADR-023): in the milliseconds between a wrong seize and the put-back a third run
# could take the free lock; it needs three runs within a few milliseconds, 3 hours after a crash.
LOCK_TTL=$((3 * 3600))
lock_file() { echo "${FIVVI_RUN_LOCK:-$NOTES_DIR/factory.lock}"; }

# 12 seconds as 12s, 25 minutes as 25m, 2 hours 5 minutes as 2h05m.
lock_age_text() {
  local s="$1"
  if [ "$s" -lt 60 ]; then echo "${s}s"
  elif [ "$s" -lt 3600 ]; then echo "$((s / 60))m"
  else printf '%dh%02dm\n' "$((s / 3600))" "$((s % 3600 / 60))"
  fi
}

# Sets LOCK_STATE (free, live, expired), LOCK_AGE (seconds since taken or refreshed), LOCK_LINE (the lock's line) and
# LOCK_RUN (the run id, empty when the lock records none); dies on a lock it cannot read.
lock_read() {
  local file started taken
  file="$(lock_file)"
  LOCK_STATE=free LOCK_AGE=0 LOCK_RUN='' LOCK_LINE=''
  [ -e "$file" ] || return 0
  LOCK_LINE="$(head -n 1 "$file" 2>/dev/null)"
  started="$(cut -d' ' -f1 <<<"$LOCK_LINE")"
  LOCK_RUN="$(sed -n 's/.* run \([0-9a-f][0-9a-f]*\)$/\1/p' <<<"$LOCK_LINE")"
  taken="$(jq -rn --arg t "$started" '$t | fromdateiso8601' 2>/dev/null)" \
    || die "the run lock $file is unreadable: remove it by hand once no run is going"
  LOCK_AGE=$(($(now_epoch) - taken))
  [ "$LOCK_AGE" -ge 0 ] || LOCK_AGE=0
  if [ "$LOCK_AGE" -gt "$LOCK_TTL" ]; then LOCK_STATE=expired; else LOCK_STATE=live; fi
}

# Dies unless the lock exists and belongs to the run id $1 (a lock without an id belongs to nobody).
lock_require_own() {
  local file="$1" run="${2:-}" verb="$3"
  [ -e "$file" ] || die "no run lock is held ($file): nothing to $verb"
  [ -n "$LOCK_RUN" ] && [ "$LOCK_RUN" = "$run" ] \
    || die "the run lock is held by another run ($file; it records $([ -n "$LOCK_RUN" ] && echo "run $LOCK_RUN" || echo "no run id")): not touching it"
}

# Renames the lock to a name of this run alone and succeeds only when it is the lock whose line is $1. When it was
# another lock (another run replaced it after it was read), puts that one back and fails. Leaves the seized file in
# $LOCK_SEIZED for the caller to remove.
lock_seize() {
  local file expected="$1"
  file="$(lock_file)"
  LOCK_SEIZED="$file.seized.$$"
  mv "$file" "$LOCK_SEIZED" 2>/dev/null || return 1
  if [ "$(head -n 1 "$LOCK_SEIZED")" = "$expected" ]; then return 0; fi
  ln "$LOCK_SEIZED" "$file" 2>/dev/null || true
  rm -f "$LOCK_SEIZED"
  return 1
}

cmd_lock() {
  case "${1:-}" in
    acquire | status) [ $# -eq 1 ] || usage ;;
    refresh | release) [ $# -le 2 ] || usage ;;
    *) usage ;;
  esac
  local file tmp now run
  file="$(lock_file)"
  case "$1" in
    status)
      lock_read
      case "$LOCK_STATE" in
        free) echo "run lock: free" ;;
        live) echo "run lock: live, last set $(lock_age_text "$LOCK_AGE") ago ($file)" ;;
        expired) echo "run lock: expired, last set $(lock_age_text "$LOCK_AGE") ago ($file); the next run takes it over" ;;
      esac ;;
    acquire)
      lock_read
      [ "$LOCK_STATE" != live ] \
        || die "another factory run is live: its lock was taken or refreshed $(lock_age_text "$LOCK_AGE") ago and expires 3h after that ($file). Report it and stop; claim nothing"
      now="$(jq -rn --argjson e "$(now_epoch)" '$e | todate')"
      mkdir -p "$(dirname "$file")"
      tmp="$(mktemp "$file.XXXXXX")"
      run="$(od -An -N8 -tx1 /dev/urandom | tr -d ' \n')"
      printf '%s %s@%s pid %s run %s\n' "$now" "${USER:-unknown}" "$(hostname -s 2>/dev/null || echo host)" "$$" "$run" >"$tmp"
      if [ "$LOCK_STATE" = expired ]; then
        if ! lock_seize "$LOCK_LINE"; then
          rm -f "$tmp"
          die "another factory run took the lock just now ($file). Report it and stop; claim nothing"
        fi
        rm -f "$LOCK_SEIZED"
        echo "run lock: the previous one expired ($(lock_age_text "$LOCK_AGE") old); taking over"
      fi
      if ! ln "$tmp" "$file" 2>/dev/null; then
        rm -f "$tmp"
        die "another factory run took the lock just now ($file). Report it and stop; claim nothing"
      fi
      rm -f "$tmp"
      echo "run lock acquired ($file)"
      echo "run id: $run" ;;
    refresh)
      lock_read
      lock_require_own "$file" "${2:-}" refresh
      now="$(jq -rn --argjson e "$(now_epoch)" '$e | todate')"
      tmp="$(mktemp "$file.XXXXXX")"
      { printf '%s ' "$now"; cut -d' ' -f2- <<<"$LOCK_LINE"; } >"$tmp"
      # Seize the lock that was read and link the new one in its place: if another run took the lock over in between,
      # the refresh fails instead of overwriting theirs.
      if ! lock_seize "$LOCK_LINE"; then
        rm -f "$tmp"
        die "the run lock was taken by another run just now ($file): stop, claim nothing, do not release"
      fi
      rm -f "$LOCK_SEIZED"
      if ! ln "$tmp" "$file" 2>/dev/null; then
        rm -f "$tmp"
        die "the run lock was taken by another run just now ($file): stop, claim nothing, do not release"
      fi
      rm -f "$tmp"
      echo "run lock refreshed ($file)" ;;
    release)
      if [ -e "$file" ]; then
        lock_read
        lock_require_own "$file" "${2:-}" release
        rm -f "$file"
        echo "run lock released"
      else
        echo "no lock held"
      fi ;;
    *) usage ;;
  esac
}

case "${1:-}" in
  lock)   shift; cmd_lock "$@" ;;
  status) shift; cmd_status "$@" ;;
  facts)  shift; cmd_facts "$@" ;;
  next)   shift; cmd_next "$@" ;;
  idle)   shift; cmd_idle "$@" ;;
  start)  shift; cmd_start "$@" ;;
  finish) shift; cmd_finish "$@" ;;
  *) usage ;;
esac
