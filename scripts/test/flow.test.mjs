const secondsAgo = (seconds) =>
  new Date(Date.parse(NOW) - seconds * 1000).toISOString().replace(/\.\d+Z$/, 'Z');
const daysAgo = (days) => secondsAgo(days * 86400);
// The record pr.sh merge writes for a high-risk PR, and (when the PR went through the queue) the queue record.
const agentMerge = (sha, reasons, queuedSha = sha) =>
  `Closes #50\n\n**High-risk agent merge:** \`${sha}\`: ${reasons}` +
  (queuedSha ? `\n\n**Merge queue:** added to the merge queue on \`${queuedSha}\`` : '');

// What the merge queue query of scripts/pr.sh answers for PR <number> (see pr.test.mjs queueFacts).
const queueRule = (number, { queued = false, removed = false, position = 1 } = {}) => ({
  match: `^api graphql -F owner=\\S+ -F name=\\S+ -F n=${number} [\\s\\S]*isInMergeQueue`,
  out: {
    data: {
      repository: {
        pullRequest: {
          state: 'OPEN',
          headRefOid: 'c'.repeat(40),
          commits: { nodes: [{ commit: { committedDate: '2026-10-19T09:00:00Z' } }] },
          body: '',
          isInMergeQueue: queued,
          mergeQueueEntry: queued ? { state: 'QUEUED', position } : null,
          autoMergeRequest: null,
          timelineItems: {
            nodes: removed
              ? [
                  {
                    __typename: 'RemovedFromMergeQueueEvent',
                    reason: 'Merge group failed',
                    createdAt: '2026-10-19T10:00:00Z',
                  },
                ]
              : [],
          },
        },
      },
    },
  },
});

