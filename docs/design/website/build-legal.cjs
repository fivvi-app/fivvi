#!/usr/bin/env node
/*
 * Turns the legal drafts in docs/legal into legal.js for the website proposal, so the pages always show
 * the current text. Open values ({{...}}) stay visible as marks. Run: node docs/design/website/build-legal.cjs
 */
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '../../..');
const pnpm = path.join(root, 'node_modules/.pnpm');
const dir = fs.readdirSync(pnpm).find((d) => /^marked@/.test(d));
const { marked } = require(path.join(pnpm, dir, 'node_modules/marked'));

function html(file) {
  const md = fs.readFileSync(path.join(root, 'docs/legal', file), 'utf8')
    .split('\n')
    .filter((l) => !/^# /.test(l) && !/^> \*\*⚠️/.test(l)) // the page has its own title and draft notice
    .join('\n');
  return marked.parse(md).replace(/\{\{([^}]+)\}\}/g, '<mark>$1</mark>').replace(/<a href="(?!http)[^"]*"[^>]*>(.*?)<\/a>/g, '$1');
}

const out = {
  privacy: [html('privacy-policy.nl.md'), html('privacy-policy.en.md')],
  terms: [html('terms.nl.md'), html('terms.en.md')],
};
fs.writeFileSync(path.join(__dirname, 'legal.js'), '/* Generated by build-legal.cjs from docs/legal. Never edit by hand. */\nwindow.LEGAL = ' + JSON.stringify(out) + ';\n');
console.log('legal.js', Math.round(fs.statSync(path.join(__dirname, 'legal.js')).size / 1024) + ' KB');
